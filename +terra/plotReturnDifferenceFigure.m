function caption = plotReturnDifferenceFigure(results, figureDirectory)
%PLOTRETURNDIFFERENCEFIGURE Figure 1: f_W of G_full and G_des, candidates, E_res.
%   caption = terra.plotReturnDifferenceFigure(results, figureDirectory)
%   draws, for the nominal and the physically perturbed configuration,
%   the diagnostic of the full and design models with every detected
%   interior candidate valley, the band edges (dotted verticals) and the
%   disk-margin requirement (top), and E_res = f_W,des - f_W,full at the
%   same frequency (bottom).

    configuration = results.configuration;
    figures = configuration.figures;
    unitConstants = terra.units();
    formats = terra.outputFormats();
    kinds = terra.valleyKinds();
    band = configuration.search.bandRadiansPerSecond;
    axisBand = [band(1) / figures.bandAxisMargin, band(2) * figures.bandAxisMargin];
    requirement = configuration.requirements.diskMarginRequirement;
    comparisons = results.modelComparison;
    columnCount = numel(comparisons);
    topRow = 1;
    bottomRow = 2;
    legendFontSize = figures.fontSize - figures.legendFontReduction;
    figureHandle = terra.createStudyFigure(configuration, figures.standardHeightCentimeters);
    statusTexts = cell(1, columnCount);

    for column = 1:columnCount
        comparison = comparisons(column);
        topAxes = terra.createPanelAxes(figureHandle, configuration, topRow, column, bottomRow, ...
            columnCount);
        hold(topAxes, 'on');
        axisLimits = figures.figure1AxisLimits;
        for edge = band
            semilogx(topAxes, edge * [1, 1], axisLimits, ':', 'Color', figures.colors.requirement, ...
                'LineWidth', figures.thinLineWidth);
        end
        fullLine = semilogx(topAxes, comparison.frequencies, comparison.fullCurve, '-', ...
            'Color', figures.colors.full, 'LineWidth', figures.lineWidth);
        designLine = semilogx(topAxes, comparison.frequencies, comparison.designCurve, '--', ...
            'Color', figures.colors.design, 'LineWidth', figures.lineWidth);
        fullInterior = comparison.fullValleys.kinds == kinds.interior;
        designInterior = comparison.designValleys.kinds == kinds.interior;
        fullMarkers = semilogx(topAxes, comparison.fullValleys.frequencies(fullInterior), ...
            comparison.fullValleys.values(fullInterior), 'o', 'Color', figures.colors.full, ...
            'MarkerSize', figures.markerSize);
        designMarkers = semilogx(topAxes, comparison.designValleys.frequencies(designInterior), ...
            comparison.designValleys.values(designInterior), 's', 'Color', figures.colors.design, ...
            'MarkerSize', figures.markerSize);
        minimumMarker = semilogx(topAxes, comparison.fullValleys.minimumFrequency, ...
            comparison.fullValleys.minimumValue, 'o', 'Color', figures.colors.confirmed, ...
            'MarkerFaceColor', figures.colors.confirmed, 'MarkerSize', figures.markerSize);
        requirementLine = semilogx(topAxes, band, requirement * [1, 1], '-.', ...
            'Color', figures.colors.requirement, 'LineWidth', figures.thinLineWidth);
        set(topAxes, 'XScale', 'log');
        xlim(topAxes, axisBand);
        ylim(topAxes, axisLimits);
        terra.styleAxes(topAxes, configuration, sprintf('(%s) %s, \\theta = %g deg', ...
            panelLetter(topRow, column, columnCount), comparison.label, ...
            comparison.operatingPoint.panelAngleDegrees), ...
            '', 'f_W(\omega) = \sigma_{min}(W_u^{-1}F_uW_u)');
        % Top right is free: f_W <= 1 above the rigid-body crossover and
        % the upper axis limit leaves room above it (vertical legends,
        % identical in MATLAB and Octave).
        if column == 1
            legend(topAxes, [fullLine, designLine, requirementLine], ...
                {'G_{full}', 'G_{des}', 'requirement 1/\gamma'}, 'Location', 'NorthEast', ...
                'FontSize', legendFontSize);
        else
            legend(topAxes, [fullMarkers, designMarkers, minimumMarker], ...
                {'full candidates', 'design candidates', 'band minimum'}, ...
                'Location', 'NorthEast', 'FontSize', legendFontSize);
        end
        statusTexts{column} = sprintf(['%s: full %s (tau_dm %.0f ms), design %s ' ...
            '(tau_dm %.0f ms)'], comparison.label, comparison.fullStability.status, ...
            comparison.fullStability.delayMarginSeconds * unitConstants.secondsToMilliseconds, ...
            comparison.designStability.status, ...
            comparison.designStability.delayMarginSeconds * unitConstants.secondsToMilliseconds);

        bottomAxes = terra.createPanelAxes(figureHandle, configuration, bottomRow, column, ...
            bottomRow, columnCount);
        hold(bottomAxes, 'on');
        residualRange = [min(comparison.residualDifference), max(comparison.residualDifference)];
        for residualFrequency = reshape(comparison.modeSelection.residualFrequencies, 1, [])
            semilogx(bottomAxes, residualFrequency * [1, 1], residualRange, '--', ...
                'Color', figures.colors.design, 'LineWidth', figures.thinLineWidth);
        end
        semilogx(bottomAxes, band, [0, 0], ':', 'Color', figures.colors.requirement);
        semilogx(bottomAxes, comparison.frequencies, comparison.residualDifference, '-', ...
            'Color', figures.colors.envelope, 'LineWidth', figures.thinLineWidth);
        set(bottomAxes, 'XScale', 'log');
        xlim(bottomAxes, axisBand);
        terra.styleAxes(bottomAxes, configuration, sprintf('(%s) E_{res} = f_{W,des} - f_{W,full}', ...
            panelLetter(bottomRow, column, columnCount)), 'Frequency \omega (rad/s)', ...
            'E_{res}(\omega)');
    end
    terra.exportStudyFigure(figureHandle, figureDirectory, 'Fig1_return_difference', configuration);

    caption = sprintf(['Figure 1. Weighted actuator-command-end diagnostic f_W for the full model ' ...
        'and the truncated design model with the same controller (top) and E_res at the same ' ...
        'physical frequency (bottom; dashed lines mark the removed residual modes). Frequency ' ...
        'unit rad/s; loop broken at the actuator command u; W_u = diag(%s); band Omega = ' ...
        '[%g, %g] rad/s (dotted verticals); requirement 1/gamma = %.4f (dash-dot); exact delay ' ...
        '%g ms. Values above %.2f (high low-frequency loop gain) are clipped. Closed-loop ' ...
        'status: %s.'], mat2str(configuration.scaling.primaryActuatorScale', ...
        formats.shortVectorDigits), band(1), band(2), requirement, ...
        configuration.operatingPoint.delaySeconds * unitConstants.secondsToMilliseconds, ...
        figures.figure1AxisLimits(2), strjoin(statusTexts, '; '));
end

function letter = panelLetter(row, column, columnCount)
%PANELLETTER Panel letter a, b, c, ... in row-major order.
    letter = char('a' + (row - 1) * columnCount + column - 1);
end
