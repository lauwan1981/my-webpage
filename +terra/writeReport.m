function writeReport(fileName, results)
%WRITEREPORT Plain-text findings with evidence levels, for the manuscript.
%   terra.writeReport(fileName, results) writes report.txt. Every number
%   comes from results; the text states which evidence each claim rests
%   on (exact formula, double-precision numerical check, finite-grid
%   empirical evidence, or declared assumption) and what is not shown.
%   Text that may be empty is appended with separate fprintf calls,
%   because MATLAB drops empty arguments from a format's value list.

    fileIdentifier = fopen(fileName, 'wt');
    if fileIdentifier < 0
        error('terra:OutputFile', 'Cannot open %s for writing.', fileName);
    end
    closer = onCleanup(@() fclose(fileIdentifier)); %#ok<NASGU>
    configuration = results.configuration;
    environment = results.environment;

    fprintf(fileIdentifier, '%s, code %s, manuscript %s, run mode %s\n', ...
        configuration.metadata.studyName, configuration.metadata.codeVersion, ...
        configuration.metadata.manuscriptVersion, configuration.metadata.runMode);
    fprintf(fileIdentifier, 'Started %s on %s %s (%s); resumed %d time(s)\n\n', ...
        environment.startedAt, environment.interpreter, environment.version, ...
        environment.platform, results.resumeCount);
    writeProvenance(fileIdentifier, configuration);
    writeSelfChecks(fileIdentifier, results.selfChecks, configuration);
    if ~isfield(results, 'caseResults')
        return;
    end
    if ~strcmp(configuration.metadata.runMode, 'full')
        fprintf(fileIdentifier, ['WARNING: reduced smoke-test run; the numbers below are not ' ...
            'publication data.\n\n']);
    end
    writeModelComparison(fileIdentifier, results);
    writePaths(fileIdentifier, results);
    writeDerivatives(fileIdentifier, results);
    writeDriftRisk(fileIdentifier, results);
    writeRemediation(fileIdentifier, results);
    writeBaseline(fileIdentifier, results);
    writeShowcase(fileIdentifier, results);
    writeLimitations(fileIdentifier);
    fprintf(fileIdentifier, '\nTotal study time %.1f s.\n', results.elapsedSeconds);
end

function writeProvenance(fileIdentifier, configuration)
%WRITEPROVENANCE Section 1: model source, controller and declared assumptions.
    formats = terra.outputFormats();
    fprintf(fileIdentifier, '1. PROVENANCE AND MANUSCRIPT ACTIONS\n');
    fprintf(fileIdentifier, '- Structural model: %s\n', configuration.provenance.structuralModel);
    fprintf(fileIdentifier, '- %s\n', configuration.provenance.notTheBenchmark);
    fprintf(fileIdentifier, '- Controller: %s\n', configuration.provenance.controller);
    fprintf(fileIdentifier, '- Damping: %s\n', configuration.provenance.dampingModel);
    fprintf(fileIdentifier, '- Implementation: %s\n', configuration.provenance.controllerImplementation);
    fprintf(fileIdentifier, ['- Declared assumptions (not in the source): rated torque %s N m ' ...
        '(W_u primary), alternate W_u %s, truncation cutoff %.4g rad/s, noise intensities ' ...
        'treated as two-sided.\n\n'], ...
        mat2str(configuration.actuator.ratedTorqueNewtonMeters', formats.shortVectorDigits), ...
        mat2str(configuration.scaling.alternateActuatorScale', formats.shortVectorDigits), ...
        configuration.truncation.designModeCutoffRadiansPerSecond);
end

function writeSelfChecks(fileIdentifier, checks, configuration)
%WRITESELFCHECKS Section 2: numbers of every model self-check.
    formats = terra.outputFormats();
    fprintf(fileIdentifier, '2. SELF-CHECKS (double precision; all passed: %d)\n', checks.passed);
    fprintf(fileIdentifier, ['- complex modal plant vs SDTlib dynamic-mass form: %.2e\n' ...
        '- additivity G_full - G_des - G_res: %.2e\n' ...
        '- fast diagnostic kernel vs loop response (alternate W_u): %.2e\n' ...
        '- modal loop vs state-space interconnection: %.2e\n' ...
        '- frequency-domain vs state-space closed-loop disturbance transfer: %.2e\n' ...
        '- %g-degree periodicity of the band minimum: %.2e\n'], checks.dynamicMassError, ...
        checks.additivityError, checks.kernelError, checks.stateSpaceLoopError, ...
        checks.closedLoopTransferError, configuration.paths.angularPeriodDegrees, ...
        checks.periodicityError);
    fprintf(fileIdentifier, '- model rigid inertia diagonal %s vs controller reference %s kg m^2\n', ...
        mat2str(checks.modelRigidInertiaDiagonal', formats.inertiaDigits), ...
        mat2str(checks.controllerReferenceInertia', formats.inertiaDigits));
    fprintf(fileIdentifier, '- coupled flexible modes (rad/s): %s, damping %s\n\n', ...
        mat2str(checks.systemModeFrequencies', formats.frequencyListDigits), ...
        mat2str(checks.systemModeDampingRatios', formats.shortVectorDigits));
end

function writeModelComparison(fileIdentifier, results)
%WRITEMODELCOMPARISON Section 3: full versus design model (Figure 1).
    unitConstants = terra.units();
    formats = terra.outputFormats();
    fprintf(fileIdentifier, '3. FULL VERSUS DESIGN MODEL (Figure 1)\n');
    for comparisonIndex = 1:numel(results.modelComparison)
        comparison = results.modelComparison(comparisonIndex);
        [peakResidual, peakIndex] = max(comparison.residualDifference);
        fprintf(fileIdentifier, ['- %s (%g deg, %g ms): full b = %.6f at %.4f rad/s (%s, ' ...
            'tau_dm %.1f ms); design b = %.6f at %.4f rad/s (%s); max E_res %.4f at %.3f rad/s; ' ...
            'residual modes %s rad/s; F_y auxiliary min %.4f at %.3f rad/s\n'], comparison.label, ...
            comparison.operatingPoint.panelAngleDegrees, ...
            comparison.operatingPoint.delaySeconds * unitConstants.secondsToMilliseconds, ...
            comparison.fullValleys.minimumValue, comparison.fullValleys.minimumFrequency, ...
            comparison.fullStability.status, ...
            comparison.fullStability.delayMarginSeconds * unitConstants.secondsToMilliseconds, ...
            comparison.designValleys.minimumValue, comparison.designValleys.minimumFrequency, ...
            comparison.designStability.status, peakResidual, comparison.frequencies(peakIndex), ...
            mat2str(comparison.modeSelection.residualFrequencies', formats.frequencyListDigits), ...
            comparison.fullMeasurementEnd.minimumValue, comparison.fullMeasurementEnd.minimumFrequency);
    end
    fprintf(fileIdentifier, ['  E_res > 0 only says that residual dynamics shrink the ' ...
        'return-difference distance at that frequency; closed-loop status and responses are ' ...
        'reported separately (Section 3.3).\n\n']);
end

function writePaths(fileIdentifier, results)
%WRITEPATHS Section 4: path envelopes, requirement violations and switches.
    requirement = results.configuration.requirements.diskMarginRequirement;
    catalogue = terra.parameterCatalogue(results.configuration);
    fprintf(fileIdentifier, '4. PARAMETER PATHS AND SWITCHES (Figure 2)\n');
    pathNames = fieldnames(results.paths);
    for pathIndex = 1:numel(pathNames)
        pathName = pathNames{pathIndex};
        unit = catalogue(strcmp({catalogue.name}, pathName)).unit;
        scaleNames = fieldnames(results.paths.(pathName));
        for scaleIndex = 1:numel(scaleNames)
            entry = results.paths.(pathName).(scaleNames{scaleIndex});
            scan = entry.scan;
            violating = scan.pathValues(scan.minimumValues < requirement);
            fprintf(fileIdentifier, ['- %s (%s), %s scaling: b ranges %.5f..%.5f; %d of %d ' ...
                'points violate b >= %.4f'], pathName, unit, scaleNames{scaleIndex}, ...
                min(scan.minimumValues), max(scan.minimumValues), numel(violating), ...
                numel(scan.pathValues), requirement);
            if ~isempty(violating)
                fprintf(fileIdentifier, ' (from %.6g to %.6g)', min(violating), max(violating));
            end
            isChecked = ~strcmp(scan.stabilityStatus, 'not_checked');
            if any(isChecked)
                notStable = sum(isChecked & ~strcmp(scan.stabilityStatus, 'stable_exact_delay'));
                fprintf(fileIdentifier, '; checked points not proven stable: %d of %d\n', ...
                    notStable, sum(isChecked));
            else
                fprintf(fileIdentifier, '; closed-loop stability not checked on this scaling\n');
            end
            for switchIndex = 1:numel(entry.switches)
                writeSwitchLine(fileIdentifier, entry.switches(switchIndex), unit);
            end
            if isempty(entry.switches)
                fprintf(fileIdentifier, '    no change of the active branch observed\n');
            end
        end
    end
    fprintf(fileIdentifier, '\n');
end

function writeSwitchLine(fileIdentifier, item, unit)
%WRITESWITCHLINE One switch record; reasons only when there are any.
    if isnan(item.parameterValue)
        fprintf(fileIdentifier, '    %s in [%.6g, %.6g] %s', item.status, item.interval(1), ...
            item.interval(2), unit);
    else
        fprintf(fileIdentifier, ['    %s at %.9g %s: b = %.6f, omega %.4f <-> %.4f rad/s, ' ...
            'slopes %.4g / %.4g per %s, third-valley gap %.4f'], item.status, ...
            item.parameterValue, unit, item.value, item.frequencies(1), item.frequencies(2), ...
            item.slopes(1), item.slopes(2), unit, item.thirdValleyGap);
    end
    if ~isempty(item.reasons)
        fprintf(fileIdentifier, ' (%s)', item.reasons);
    end
    fprintf(fileIdentifier, '\n');
end

function writeDerivatives(fileIdentifier, results)
%WRITEDERIVATIVES Section 5: predicted versus secant one-sided derivatives.
    fprintf(fileIdentifier, '5. ONE-SIDED DERIVATIVE VALIDATION (Section 4.3)\n');
    for locationIndex = 1:numel(results.derivativeValidation)
        validation = results.derivativeValidation(locationIndex);
        parameterNames = unique({validation.rows.parameterName});
        fprintf(fileIdentifier, '- %s (near-active valleys: %d)\n', validation.label, ...
            validation.activeCount);
        for parameterIndex = 1:numel(parameterNames)
            for direction = [1, -1]
                selected = validation.rows(strcmp({validation.rows.parameterName}, ...
                    parameterNames{parameterIndex}) & [validation.rows.direction] == direction);
                fprintf(fileIdentifier, ['    %s %+d: predicted %.6g, smallest-step secant %.6g, ' ...
                    'error %.2e (largest step %.2e)\n'], parameterNames{parameterIndex}, direction, ...
                    selected(end).predicted, selected(end).secant, selected(end).absoluteError, ...
                    selected(1).absoluteError);
            end
        end
    end
    fprintf(fileIdentifier, '\n');
end

function writeDriftRisk(fileIdentifier, results)
%WRITEDRIFTRISK Section 6: drift-risk table sorted by first-order degradation.
    fprintf(fileIdentifier, '6. DRIFT RISK OF PHYSICAL PARAMETERS (D = h d, R = max(0, -D))\n');
    for riskIndex = 1:numel(results.driftRisk)
        risk = results.driftRisk(riskIndex);
        fprintf(fileIdentifier, '- %s: b = %.6f at %.4f rad/s\n', risk.label, risk.baseValue, ...
            risk.baseFrequency);
        degradation = max([risk.rows.degradationPositive; risk.rows.degradationNegative], [], 1);
        [~, order] = sort(degradation, 'descend');
        for rowIndex = order
            item = risk.rows(rowIndex);
            rowText = [sprintf('    %-16s h=%-8.4g D+ %+.5f (finite %+.5f', item.parameterName, ...
                item.stepSize, item.changePositive, item.actualChangePositive), ...
                migrationMark(item.migratesPositive), ...
                sprintf(')  D- %+.5f (finite %+.5f', item.changeNegative, item.actualChangeNegative), ...
                migrationMark(item.migratesNegative), ')'];
            fprintf(fileIdentifier, '%s\n', rowText);
        end
    end
    fprintf(fileIdentifier, '  * = the finite step moves the band minimum to another valley.\n\n');
end

function mark = migrationMark(migrates)
%MIGRATIONMARK Asterisk when a finite step moves the band minimum.
    if migrates
        mark = ' *';
    else
        mark = '';
    end
end

function writeRemediation(fileIdentifier, results)
%WRITEREMEDIATION Section 7: screening-rule statistics and residual levels.
    remediation = results.configuration.remediation;
    formats = terra.outputFormats();
    fprintf(fileIdentifier, ['7. REMEDIATION SCREENING (equal budgets, all moves verified for ' ...
        'benchmarking)\n']);
    for ruleIndex = 1:numel(remediation.ruleNames)
        fprintf(fileIdentifier, '  rule %-16s %s\n', remediation.ruleNames{ruleIndex}, ...
            remediation.ruleDescriptions{ruleIndex});
    end
    summary = terra.summarizeRemediation(results);
    for summaryIndex = 1:numel(summary)
        item = summary(summaryIndex);
        if ~strcmp(item.family, 'all')
            continue;
        end
        fprintf(fileIdentifier, ['- %-16s top-%d: optimum found %d/%d, worst regret %.5f, ' ...
            'median cost %.0f%% of exhaustive\n'], item.rule, item.budget, item.matchCount, ...
            item.caseCount, item.worstRegret, formats.fractionToPercent * item.medianCostFraction);
    end
    caseResults = results.caseResults;
    caseCount = numel(caseResults);
    levels = [caseResults.levels];
    fprintf(fileIdentifier, ['- Residual dynamics (Section 4.3): a residual-mode valley is the ' ...
        'band minimum in %d/%d cases and in the near-active set in %d/%d cases; the ' ...
        'design-model decision differs from the full-model %s decision in %d/%d cases; ' ...
        'observable pointing change (>%.0f%%) in %d/%d cases.\n'], ...
        sum([levels.residualValleyIsBandMinimum]), caseCount, ...
        sum([levels.residualValleyActive]), caseCount, remediation.primaryRule, ...
        sum([levels.decisionChanged]), caseCount, ...
        formats.fractionToPercent * remediation.observablePointingRelativeChange, ...
        sum([levels.pointingChangeObservable]), caseCount);
    worse = 0;
    for caseIndex = 1:caseCount
        if caseResults(caseIndex).designDecision.fullModelValue < ...
                caseResults(caseIndex).fullSummary.minimumValue - remediation.decisionEqualityTolerance
            worse = worse + 1;
        end
    end
    fprintf(fileIdentifier, ['- The design-model decision lowers the full-model margin in %d/%d ' ...
        'cases.\n\n'], worse, caseCount);
end

function writeBaseline(fileIdentifier, results)
%WRITEBASELINE Section 8: equal-error dense baseline (Table 2).
    totals = terra.summarizeDenseBaseline(results);
    fprintf(fileIdentifier, '8. DENSE BASELINE (Table 2)\n');
    fprintf(fileIdentifier, ['- detection: method %d/%d (extra %d), dense %d/%d (extra %d); max ' ...
        'band-minimum error method %.2e, dense %.2e; dense grid missed the target in %d of %d ' ...
        'cases (largest rung used %d points)\n- median evaluations method %d vs dense %d ' ...
        '(ratio %.1f); median time %.1f ms vs %.1f ms (ratio %.1f); shared model build %.1f ms\n' ...
        '- switch location error: method {%s}; dense {%s}\n' ...
        '- single main crossover check misses the active valley in %d/%d cases (max ' ...
        'overestimate %.4f)\n\n'], totals.methodMatched, totals.referenceValleys, ...
        totals.methodExtra, totals.denseMatched, totals.referenceValleys, totals.denseExtra, ...
        totals.methodMaximumError, totals.denseMaximumError, totals.denseFailures, ...
        totals.caseCount, totals.denseMaximumPoints, round(totals.methodMedianEvaluations), ...
        round(totals.denseMedianEvaluations), totals.medianEvaluationRatio, ...
        totals.methodMedianMilliseconds, totals.denseMedianMilliseconds, totals.medianTimeRatio, ...
        totals.modelMedianMilliseconds, totals.methodSwitchErrorText, totals.denseSwitchErrorText, ...
        totals.crossoverMissCount, totals.caseCount, totals.crossoverMaximumOverestimate);
end

function writeShowcase(fileIdentifier, results)
%WRITESHOWCASE Section 9: Table 1 rows and the Figure 3 decision.
    unitConstants = terra.units();
    fprintf(fileIdentifier, '9. TABLE 1 ROWS AND FIGURE 3\n');
    rows = results.showcase.table1Rows;
    for rowIndex = 1:numel(rows)
        row = rows(rowIndex);
        fprintf(fileIdentifier, ['- %-31s %-18s b=%.5f at %.4f rad/s, %s, tau_dm %.1f ms, ' ...
            'GM %.2f dB PM %.1f deg, APE ratio %.2f, step peak %.0f urad\n'], row.label, ...
            row.moveLabel, row.summary.minimumValue, row.summary.minimumFrequency, ...
            row.stability.status, row.stability.delayMarginSeconds * unitConstants.secondsToMilliseconds, ...
            row.guaranteedMargins.upperGainMarginDecibels, row.guaranteedMargins.phaseMarginDegrees, ...
            max(row.metrics.absolutePointingErrorRatio), ...
            max(row.simulation.peakAttitudeRadians) * unitConstants.radiansToMicroradians);
    end
    roles = terra.figureRoles();
    for entryIndex = 1:numel(results.showcase.figure3)
        entry = results.showcase.figure3(entryIndex);
        fprintf(fileIdentifier, ['- Figure 3, %s: conventional "%s" b=%.5f vs active-branch "%s" ' ...
            'b=%.5f (difference %+.5f); verifiably different decision: %d\n'], entry.label, ...
            entry.moveLabels{roles.conventional}, entry.bandMinimum(roles.conventional), ...
            entry.moveLabels{roles.method}, entry.bandMinimum(roles.method), ...
            entry.marginDifference, entry.isVerifiablyDifferent);
    end
    fprintf(fileIdentifier, '\n');
end

function writeLimitations(fileIdentifier)
%WRITELIMITATIONS Section 10: evidence levels and what is not covered.
    fprintf(fileIdentifier, '10. EVIDENCE LEVELS AND LIMITATIONS\n');
    fprintf(fileIdentifier, ['- Exact: singular-value derivative formulas, delay-margin crossing ' ...
        'condition, additivity of the complex modal truncation.\n' ...
        '- Numerical (double precision, not interval arithmetic): eigenvalues, Newton-refined ' ...
        'exact-delay roots, tail bounds, all self-checks.\n' ...
        '- Empirical (finite grids): completeness of the valley lists, switch locations, ' ...
        'screening statistics, timing (this machine only).\n' ...
        '- Not covered: sampled-data implementation, actuator rate limits and friction, model ' ...
        'uncertainty beyond the listed corners, flight data, physical attribution of valleys ' ...
        'to modes (counterfactuals only).\n']);
end
