function validateConfiguration(configuration)
%VALIDATECONFIGURATION Reject structurally invalid study assumptions.
%   terra.validateConfiguration(configuration) raises an error with a
%   descriptive message if any declared value is outside its physical or
%   numerical domain. It runs before any computation.

    structure = configuration.structure;
    search = configuration.search;
    band = search.bandRadiansPerSecond;
    requireCondition(numel(band) == 2 && all(band > 0) && band(2) > band(1), ...
        'search band must be [low, high] with 0 < low < high');
    requireCondition(all(structure.cantileverModeFrequenciesRadiansPerSecond > 0), ...
        'cantilever mode frequencies must be positive');
    requireCondition(structure.cantileverModeDampingRatio > 0, ...
        'cantilever modal damping must be positive');
    requireCondition(min(eig(structure.hubInertiaKilogramMetersSquared)) > 0, ...
        'hub inertia must be positive definite');
    requireCondition(all(configuration.controller.dampingRatio > 0) && ...
        all(configuration.controller.rolloffFrequencyRadiansPerSecond > 0), ...
        'controller damping and roll-off must be positive');
    requireCondition(all(configuration.scaling.primaryActuatorScale > 0) && ...
        all(configuration.scaling.alternateActuatorScale > 0), ...
        'actuator scales must be positive');
    requireCondition(all(configuration.actuator.ratedTorqueNewtonMeters > 0), ...
        'rated torques must be positive');
    requireCondition(configuration.operatingPoint.delaySeconds >= 0, ...
        'nominal delay must be non-negative');
    % A sampled interior minimum needs a point on each side.
    minimumGridPointCount = 3;
    requireCondition(search.initialGridPointCount >= minimumGridPointCount, ...
        sprintf('initial grid needs at least %d points', minimumGridPointCount));
    requireCondition(configuration.stability.chebyshevConvergenceOrder > ...
        configuration.stability.chebyshevOrder, ...
        'convergence check needs a higher Chebyshev order');
    % Observed convergence orders use the two smallest secant steps.
    minimumSecantStepCount = 2;
    requireCondition(numel(configuration.derivatives.secantStepFractions) >= ...
        minimumSecantStepCount, 'derivative validation needs at least two secant steps');
    remediation = configuration.remediation;
    requireCondition(any(strcmp(remediation.designModelRule, remediation.ruleNames)), ...
        'design-model rule must be one of ruleNames');
    requireCondition(any(strcmp(remediation.conventionalRule, remediation.ruleNames)), ...
        'conventional rule must be one of ruleNames');
    requireCondition(all(diff(configuration.baseline.denseGridLadder) > 0), ...
        'dense ladder must be increasing');
    requireCondition(any(strcmp(configuration.remediation.primaryRule, ...
        configuration.remediation.ruleNames)), 'primary rule must be one of ruleNames');
    requireCondition(any(configuration.remediation.screeningBudgets == ...
        configuration.remediation.primaryBudget), 'primary budget must be a screening budget');
end

function requireCondition(condition, message)
%REQUIRECONDITION Raise terra:InvalidConfiguration if condition is false.
    if ~condition
        error('terra:InvalidConfiguration', 'Invalid configuration: %s.', message);
    end
end
