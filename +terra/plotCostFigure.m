function caption = plotCostFigure(results, figureDirectory)
%PLOTCOSTFIGURE Figure S1: equal-error cost of method and dense baseline.
%   caption = terra.plotCostFigure(results, figureDirectory) plots, per
%   case, the f_W evaluations and wall time of the adaptive method and of
%   the smallest plain dense grid reaching the same band-minimum error
%   with complete valley detection (Table 2), on the same machine. Cases
%   in which even the largest rung missed the target are marked x.

    configuration = results.configuration;
    figures = configuration.figures;
    unitConstants = terra.units();
    comparisons = results.denseBaseline;
    caseNumbers = 1:numel(comparisons);
    reached = [comparisons.denseReachedTarget];
    legendReserve = figures.layout.legendColumnCentimeters;
    figureHandle = terra.createStudyFigure(configuration, figures.standardHeightCentimeters);

    evaluationAxes = terra.createPanelAxes(figureHandle, configuration, 1, 1, 2, 1, 1, legendReserve);
    hold(evaluationAxes, 'on');
    methodHandle = semilogy(evaluationAxes, caseNumbers, [comparisons.methodEvaluations], '-o', ...
        'Color', figures.colors.methodMove, 'MarkerSize', figures.markerSize);
    denseEvaluations = [comparisons.denseEvaluations];
    denseHandle = semilogy(evaluationAxes, caseNumbers, denseEvaluations, '-s', ...
        'Color', figures.colors.baselineMove, 'MarkerSize', figures.markerSize);
    referenceHandle = semilogy(evaluationAxes, caseNumbers, [comparisons.referenceEvaluations], ':', ...
        'Color', figures.colors.requirement);
    handles = [methodHandle, denseHandle, referenceHandle];
    labels = {'adaptive method', 'dense grid, equal error', 'independent reference'};
    if any(~reached)
        handles(end + 1) = semilogy(evaluationAxes, caseNumbers(~reached), ...
            denseEvaluations(~reached), 'x', 'Color', figures.colors.confirmed, ...
            'MarkerSize', figures.markerSize + 2);
        labels{end + 1} = 'dense: target missed';
    end
    set(evaluationAxes, 'YScale', 'log');
    terra.styleAxes(evaluationAxes, configuration, '(a) f_W evaluations at equal error', '', ...
        'evaluations');
    terra.styleCaseAxis(evaluationAxes, configuration, results.cases, false);
    terra.addLegendPanel(figureHandle, configuration, evaluationAxes, handles, labels);

    timeAxes = terra.createPanelAxes(figureHandle, configuration, 2, 1, 2, 1, 1, legendReserve);
    hold(timeAxes, 'on');
    milliseconds = unitConstants.secondsToMilliseconds;
    timeHandles = [ ...
        semilogy(timeAxes, caseNumbers, [comparisons.methodSeconds] * milliseconds, '-o', ...
            'Color', figures.colors.methodMove, 'MarkerSize', figures.markerSize), ...
        semilogy(timeAxes, caseNumbers, [comparisons.denseSeconds] * milliseconds, '-s', ...
            'Color', figures.colors.baselineMove, 'MarkerSize', figures.markerSize), ...
        semilogy(timeAxes, caseNumbers, [comparisons.modelSeconds] * milliseconds, ':^', ...
            'Color', figures.colors.requirement, 'MarkerSize', figures.markerSize - 1)];
    set(timeAxes, 'YScale', 'log');
    terra.styleAxes(timeAxes, configuration, '(b) wall time (searches: median of repeats)', ...
        '', 'time (ms)');
    terra.styleCaseAxis(timeAxes, configuration, results.cases, true);
    terra.addLegendPanel(figureHandle, configuration, timeAxes, timeHandles, ...
        {'adaptive method', 'dense grid, equal error', 'shared model build'});
    terra.exportStudyFigure(figureHandle, figureDirectory, 'FigS1_cost_comparison', configuration);

    caption = sprintf(['Figure S1. Cost at equal accuracy: band-minimum error <= %.0e and every ' ...
        'reference valley detected. Both methods use the same evaluator, model and band; ' ...
        'search times are medians of %d repeats on %s %s (%s); the shared model build is ' ...
        'timed once per case. Cases marked x did not reach the target even with %d points. ' ...
        'Case labels are listed under Figure S2.'], ...
        configuration.baseline.targetMinimumValueError, ...
        configuration.baseline.timingRepeatCount, results.environment.interpreter, ...
        results.environment.version, results.environment.platform, ...
        configuration.baseline.denseGridLadder(end));
end
