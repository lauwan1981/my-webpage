function writeResultTables(tableDirectory, results)
%WRITERESULTTABLES Every numeric result as CSV, plus tables.md for the paper.
%   terra.writeResultTables(tableDirectory, results) writes
%     table1_cases.csv              Table 1 (six predeclared rows)
%     table2_dense_baseline.csv     Table 2 per case
%     table2_switch_locations.csv   switch-location errors
%     remediation_cases.csv         decisions of every rule per case
%     remediation_summary.csv       rule statistics per case family
%     path_valleys.csv / path_summary.csv / switches.csv
%     derivative_validation.csv / drift_risk.csv / stability.csv
%     model_comparison.csv          Figure 1 valley lists
%     mode_removal_counterfactual.csv   band minimum with one mode removed
%     tables.md                     formatted Tables 1 and 2 with notes

    writeTable1(tableDirectory, results);
    writeTable2(tableDirectory, results);
    writeRemediationTables(tableDirectory, results);
    writePathTables(tableDirectory, results);
    writeDerivativeTables(tableDirectory, results);
    writeStabilityTable(tableDirectory, results);
    writeModelComparisonTable(tableDirectory, results);
    writeMarkdownTables(fullfile(tableDirectory, 'tables.md'), results);
end

%% Table 1 -------------------------------------------------------------------------------
