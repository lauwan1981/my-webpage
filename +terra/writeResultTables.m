    unitConstants = terra.units();
    rows = results.showcase.table1Rows;
    header = {'row', 'case', 'model', 'controller', 'omega_star_rad_s', 'b_omega', ...
        'error_bound', 'spectral_gap', 'second_valley_b', 'second_valley_omega_rad_s', ...
        'near_active_count', 'row_parameter', 'row_parameter_step', 'D_plus', 'D_minus', ...
        'adjusted_parameter', 'screening_D_plus', 'screening_D_minus', 'closed_loop_status', ...
        'rightmost_root_real_1_per_s', 'delay_margin_ms', 'guaranteed_gain_margin_dB', ...
        'guaranteed_phase_margin_deg', 'static_APE_ratio_max', ...
        'peak_pointing_gain_urad_per_Nm', 'noise_pointing_rms_urad_max', ...
        'noise_command_rms_Nm_max', 'step_peak_attitude_urad_max', ...
        'step_steady_APE_ratio_max', 'step_peak_command_to_rated_max', ...
        'saturation_fraction', 'plant_states'};
    cells = cell(numel(rows), numel(header));
    for rowIndex = 1:numel(rows)
        row = rows(rowIndex);
        cells(rowIndex, :) = {row.label, row.caseLabel, row.modeSet, row.moveLabel, ...
            row.summary.minimumFrequency, row.summary.minimumValue, row.summary.errorBound, ...
            row.summary.spectralGap, row.summary.secondValue, row.summary.secondFrequency, ...
            row.summary.activeCount, row.rowParameter, row.rowStep, row.driftChangePositive, ...
            row.driftChangeNegative, row.adjustedParameter, row.screeningChangePositive, ...
            row.screeningChangeNegative, row.stability.status, row.stability.rightmostRealPart, ...
            row.stability.delayMarginSeconds * unitConstants.secondsToMilliseconds, ...
            row.guaranteedMargins.upperGainMarginDecibels, row.guaranteedMargins.phaseMarginDegrees, ...
            max(row.metrics.absolutePointingErrorRatio), ...
            row.metrics.peakPointingGain * unitConstants.radiansToMicroradians, ...
            max(row.metrics.noisePointingRmsRadians) * unitConstants.radiansToMicroradians, ...
