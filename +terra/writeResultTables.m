%% Remediation -------------------------------------------------------------------------------
function writeRemediationTables(tableDirectory, results)
%WRITEREMEDIATIONTABLES Decisions per case and rule statistics as CSV.
    unitConstants = terra.units();
    configuration = results.configuration;
    remediation = configuration.remediation;
    requirement = configuration.requirements.diskMarginRequirement;
    header = {'case', 'family', 'b_unchanged', 'omega_star_rad_s', 'meets_disk_margin_requirement', ...
        'residual_valley_is_band_minimum', 'residual_valley_active', 'oracle_move', 'oracle_b'};
    for ruleIndex = 1:numel(remediation.ruleNames)
        for budget = remediation.screeningBudgets
            prefix = sprintf('%s_top%d', remediation.ruleNames{ruleIndex}, budget);
            header = [header, {[prefix, '_move'], [prefix, '_b'], [prefix, '_regret'], ...
                [prefix, '_evaluations'], [prefix, '_seconds']}]; %#ok<AGROW>
        end
    end
    header = [header, {'design_model_move', 'design_model_full_b', ...
        'decision_changed_by_residual', 'pointing_relative_change', 'pointing_change_observable', ...
        'exhaustive_evaluations', 'exhaustive_seconds', 'closed_loop_status', 'delay_margin_ms'}];
    caseResults = results.caseResults;
    cells = cell(numel(caseResults), numel(header));
    for caseIndex = 1:numel(caseResults)
        item = caseResults(caseIndex);
        rowCells = {item.label, item.family, item.fullSummary.minimumValue, ...
            item.fullSummary.minimumFrequency, item.fullSummary.minimumValue >= requirement, ...
            item.levels.residualValleyIsBandMinimum, item.levels.residualValleyActive, ...
            item.oracle.code, item.oracle.value};
        for ruleIndex = 1:numel(remediation.ruleNames)
            for budget = remediation.screeningBudgets
                selection = item.selections.(sprintf('%s_top%d', remediation.ruleNames{ruleIndex}, budget));
                rowCells = [rowCells, {selection.code, selection.value, selection.regret, ...
                    selection.accountedEvaluations, selection.accountedSeconds}]; %#ok<AGROW>
            end
        end
        rowCells = [rowCells, {item.designDecision.code, item.designDecision.fullModelValue, ...
            item.levels.decisionChanged, item.levels.pointingRelativeChange, ...
            item.levels.pointingChangeObservable, item.costs.exhaustiveEvaluations, ...
            item.costs.exhaustiveSeconds, item.stabilityFull.status, ...
            item.stabilityFull.delayMarginSeconds * unitConstants.secondsToMilliseconds}]; %#ok<AGROW>
        cells(caseIndex, :) = rowCells;
    end
    terra.writeCsvTable(fullfile(tableDirectory, 'remediation_cases.csv'), header, cells);

    summary = terra.summarizeRemediation(results);
    summaryHeader = {'family', 'rule', 'budget', 'cases', 'matches_oracle', 'worst_regret', ...
        'mean_regret', 'median_evaluations', 'median_seconds', 'median_cost_fraction_of_exhaustive'};
    summaryCells = cell(numel(summary), numel(summaryHeader));
    for summaryIndex = 1:numel(summary)
        item = summary(summaryIndex);
        summaryCells(summaryIndex, :) = {item.family, item.rule, item.budget, item.caseCount, ...
            item.matchCount, item.worstRegret, item.meanRegret, item.medianEvaluations, ...
            item.medianSeconds, item.medianCostFraction};
    end
    terra.writeCsvTable(fullfile(tableDirectory, 'remediation_summary.csv'), summaryHeader, summaryCells);
end

%% Paths and switches ----------------------------------------------------------------------
function writePathTables(tableDirectory, results)
%WRITEPATHTABLES Every path valley, path summaries and switches as CSV.
    unitConstants = terra.units();
    requirement = results.configuration.requirements.diskMarginRequirement;
    valleyHeader = {'path', 'scaling', 'parameter', 'frequency_rad_s', 'value', 'kind', ...
        'spectral_gap', 'curvature_log', 'nondegenerate', 'error_bound', 'unresolved', ...
        'edge_descending', 'refinement_delta', 'near_active', 'branch_id'};
    summaryHeader = {'path', 'scaling', 'parameter', 'b_min', 'omega_star_rad_s', ...
        'active_branch', 'meets_disk_margin_requirement', 'closed_loop_status', 'delay_margin_ms'};
    switchHeader = {'path', 'scaling', 'interval_low', 'interval_high', 'parameter_value', 'b', ...
        'omega_1_rad_s', 'omega_2_rad_s', 'equality_error', 'third_valley_gap', 'slope_1', ...
        'slope_2', 'slope_difference', 'swap_confirmed', 'nondegenerate_1', 'nondegenerate_2', ...
        'status', 'reasons'};
    valleyCells = cell(0, numel(valleyHeader));
    summaryCells = cell(0, numel(summaryHeader));
    switchCells = cell(0, numel(switchHeader));
    pathNames = fieldnames(results.paths);
    for pathIndex = 1:numel(pathNames)
        scaleNames = fieldnames(results.paths.(pathNames{pathIndex}));
        for scaleIndex = 1:numel(scaleNames)
            entry = results.paths.(pathNames{pathIndex}).(scaleNames{scaleIndex});
            scan = entry.scan;
            tracks = entry.tracks;
            for pointIndex = 1:numel(scan.pathValues)
                valleys = scan.valleys{pointIndex};
                for slot = 1:numel(valleys.values)
                    branchId = find(tracks.frequency(pointIndex, :) == valleys.frequencies(slot), 1);
                    if isempty(branchId)
                        branchId = 0;
                    end
                    valleyCells(end + 1, :) = {pathNames{pathIndex}, scaleNames{scaleIndex}, ...
                        scan.pathValues(pointIndex), valleys.frequencies(slot), valleys.values(slot), ...
                        valleys.kinds(slot), valleys.spectralGaps(slot), valleys.curvatures(slot), ...
                        valleys.isNondegenerate(slot), valleys.errorBounds(slot), ...
                        valleys.isUnresolved(slot), valleys.isBoundaryDescending(slot), ...
                        valleys.refinementDeltas(slot), any(valleys.activeIndices == slot), ...
                        branchId}; %#ok<AGROW>
                end
                summaryCells(end + 1, :) = {pathNames{pathIndex}, scaleNames{scaleIndex}, ...
                    scan.pathValues(pointIndex), scan.minimumValues(pointIndex), ...
                    scan.minimumFrequencies(pointIndex), tracks.activeBranch(pointIndex), ...
                    scan.minimumValues(pointIndex) >= requirement, scan.stabilityStatus{pointIndex}, ...
                    scan.delayMarginSeconds(pointIndex) * unitConstants.secondsToMilliseconds}; %#ok<AGROW>
            end
            for switchIndex = 1:numel(entry.switches)
                item = entry.switches(switchIndex);
                switchCells(end + 1, :) = {pathNames{pathIndex}, scaleNames{scaleIndex}, ...
                    item.interval(1), item.interval(2), item.parameterValue, item.value, ...
                    item.frequencies(1), item.frequencies(2), item.equalityError, ...
                    item.thirdValleyGap, item.slopes(1), item.slopes(2), item.slopeDifference, ...
                    item.swapConfirmed, item.nondegenerate(1), item.nondegenerate(2), ...
                    item.status, item.reasons}; %#ok<AGROW>
            end
        end
    end
    terra.writeCsvTable(fullfile(tableDirectory, 'path_valleys.csv'), valleyHeader, valleyCells);
    terra.writeCsvTable(fullfile(tableDirectory, 'path_summary.csv'), summaryHeader, summaryCells);
    terra.writeCsvTable(fullfile(tableDirectory, 'switches.csv'), switchHeader, switchCells);
end

%% Derivatives and drift risk -------------------------------------------------------------------
function writeDerivativeTables(tableDirectory, results)
%WRITEDERIVATIVETABLES Secant validation rows and drift-risk rows as CSV.
    header = {'location', 'parameter', 'direction', 'step', 'predicted_one_sided_derivative', ...
        'one_sided_secant', 'absolute_error'};
    cells = cell(0, numel(header));
    for locationIndex = 1:numel(results.derivativeValidation)
        validation = results.derivativeValidation(locationIndex);
        for rowIndex = 1:numel(validation.rows)
            item = validation.rows(rowIndex);
            cells(end + 1, :) = {validation.label, item.parameterName, item.direction, item.step, ...
                item.predicted, item.secant, item.absoluteError}; %#ok<AGROW>
        end
    end
    terra.writeCsvTable(fullfile(tableDirectory, 'derivative_validation.csv'), header, cells);

    driftHeader = {'location', 'parameter', 'unit', 'h', 'd_plus', 'd_minus', 'D_plus', 'D_minus', ...
        'R_plus', 'R_minus', 'branch_aware_change_plus', 'branch_aware_change_minus', ...
        'finite_step_change_plus', 'finite_step_change_minus', 'migrates_plus', 'migrates_minus'};
    driftCells = cell(0, numel(driftHeader));
    for locationIndex = 1:numel(results.driftRisk)
        risk = results.driftRisk(locationIndex);
        for rowIndex = 1:numel(risk.rows)
            item = risk.rows(rowIndex);
            driftCells(end + 1, :) = {risk.label, item.parameterName, item.unit, item.stepSize, ...
                item.unitDerivativePositive, item.unitDerivativeNegative, item.changePositive, ...
                item.changeNegative, item.degradationPositive, item.degradationNegative, ...
                item.branchAwarePositive, item.branchAwareNegative, item.actualChangePositive, ...
                item.actualChangeNegative, item.migratesPositive, item.migratesNegative}; %#ok<AGROW>
        end
    end
    terra.writeCsvTable(fullfile(tableDirectory, 'drift_risk.csv'), driftHeader, driftCells);
end

%% Stability -------------------------------------------------------------------------------------
function writeStabilityTable(tableDirectory, results)
%WRITESTABILITYTABLE Closed-loop status of every evaluated configuration.
    unitConstants = terra.units();
    header = {'case', 'configuration', 'status', 'zero_delay_max_real_1_per_s', ...
        'rightmost_exact_delay_real_1_per_s', 'delay_margin_ms', 'critical_frequency_rad_s', ...
        'search_band_certified', 'unverified_candidate_roots'};
    cells = cell(0, numel(header));
    for caseIndex = 1:numel(results.caseResults)
        item = results.caseResults(caseIndex);
        cells(end + 1, :) = stabilityCells(item.label, 'design model, unchanged', ...
            item.stabilityDesign, unitConstants); %#ok<AGROW>
        for decisionIndex = 1:numel(item.evaluatedDecisions)
            decision = item.evaluatedDecisions(decisionIndex);
            cells(end + 1, :) = stabilityCells(item.label, ['full model, ', decision.label], ...
                decision.stability, unitConstants); %#ok<AGROW>
        end
    end
    terra.writeCsvTable(fullfile(tableDirectory, 'stability.csv'), header, cells);
end

function cells = stabilityCells(caseLabel, configurationLabel, stability, unitConstants)
%STABILITYCELLS One stability.csv row.
    cells = {caseLabel, configurationLabel, stability.status, stability.zeroDelayMaximumRealPart, ...
        stability.rightmostRealPart, stability.delayMarginSeconds * unitConstants.secondsToMilliseconds, ...
        stability.criticalFrequency, stability.isBandCertified, stability.unverifiedRootCount};
end

%% Figure 1 data ---------------------------------------------------------------------------------
function writeModelComparisonTable(tableDirectory, results)
%WRITEMODELCOMPARISONTABLE Figure 1 valley lists and mode-removal counterfactuals.
    header = {'configuration', 'model', 'frequency_rad_s', 'value', 'kind', 'spectral_gap', ...
        'error_bound'};
    cells = cell(0, numel(header));
    counterfactualHeader = {'configuration', 'removed_mode_natural_frequency_rad_s', ...
        'band_minimum_frequency_rad_s', 'band_minimum'};
    counterfactualCells = cell(0, numel(counterfactualHeader));
    for comparisonIndex = 1:numel(results.modelComparison)
        comparison = results.modelComparison(comparisonIndex);
        modelNames = {'full', 'design'};
        valleySets = {comparison.fullValleys, comparison.designValleys};
        for modelIndex = 1:numel(modelNames)
            valleys = valleySets{modelIndex};
            for slot = 1:numel(valleys.values)
                cells(end + 1, :) = {comparison.label, modelNames{modelIndex}, ...
                    valleys.frequencies(slot), valleys.values(slot), valleys.kinds(slot), ...
                    valleys.spectralGaps(slot), valleys.errorBounds(slot)}; %#ok<AGROW>
            end
        end
        for rowIndex = 1:size(comparison.singleModeRemoval, 1)
            counterfactualCells(end + 1, :) = [{comparison.label}, ...
                num2cell(comparison.singleModeRemoval(rowIndex, :))]; %#ok<AGROW>
        end
    end
    terra.writeCsvTable(fullfile(tableDirectory, 'model_comparison.csv'), header, cells);
    terra.writeCsvTable(fullfile(tableDirectory, 'mode_removal_counterfactual.csv'), ...
        counterfactualHeader, counterfactualCells);
end

%% Markdown ------------------------------------------------------------------------------------
function writeMarkdownTables(fileName, results)
%WRITEMARKDOWNTABLES Formatted Tables 1 and 2 with notes for the manuscript.
    unitConstants = terra.units();
    formats = terra.outputFormats();
    configuration = results.configuration;
    fileIdentifier = fopen(fileName, 'wt');
    if fileIdentifier < 0
        error('terra:OutputFile', 'Cannot open %s for writing.', fileName);
    end
    closer = onCleanup(@() fclose(fileIdentifier)); %#ok<NASGU>

    rows = results.showcase.table1Rows;
    fprintf(fileIdentifier, '# Table 1. Predeclared cases (one model and controller version)\n\n');
    header = {'Case', 'Controller', 'Active valley omega* (rad/s)', 'b_Omega / spectral gap', ...
        'D+ / D- (parameter, h)', 'Closed loop (exact delay)', 'Pointing / command'};
    cells = cell(numel(rows), numel(header));
    for rowIndex = 1:numel(rows)
        row = rows(rowIndex);
        if isempty(row.adjustedParameter)
            changeText = sprintf('%+.3g / %+.3g (%s, %g)', row.driftChangePositive, ...
                row.driftChangeNegative, row.rowParameter, row.rowStep);
        else
            changeText = sprintf('%+.3g / %+.3g (%s, %g); %s: %+.3g / %+.3g', ...
                row.driftChangePositive, row.driftChangeNegative, row.rowParameter, ...
                row.rowStep, row.adjustedParameter, row.screeningChangePositive, ...
                row.screeningChangeNegative);
        end
        cells(rowIndex, :) = {row.label, row.moveLabel, ...
            sprintf('%.4f', row.summary.minimumFrequency), ...
            sprintf('%.5f / %.3g', row.summary.minimumValue, row.summary.spectralGap), changeText, ...
            sprintf('%s; max Re %.4f 1/s; tau_dm %.1f ms (remaining %.1f ms)', ...
                row.stability.status, row.stability.rightmostRealPart, ...
                row.stability.delayMarginSeconds * unitConstants.secondsToMilliseconds, ...
                (row.stability.delayMarginSeconds - row.stability.delaySeconds) * ...
                unitConstants.secondsToMilliseconds), ...
            sprintf(['APE ratio %.2f; noise jitter %.1f urad; step peak %.0f urad; ' ...
                'noise torque %.3f N m; peak/rated %.3f'], ...
                max(row.metrics.absolutePointingErrorRatio), ...
                max(row.metrics.noisePointingRmsRadians) * unitConstants.radiansToMicroradians, ...
                max(row.simulation.peakAttitudeRadians) * unitConstants.radiansToMicroradians, ...
                max(row.metrics.noiseCommandRmsNewtonMeters), max(row.simulation.peakCommandRatio))};
    end
    terra.writeMarkdownTable(fileIdentifier, header, cells);
    fprintf(fileIdentifier, ['Notes. Model: %s Plant order %d (full) / %d (design); closed loop ' ...
        '%d states plus exact delay. Band Omega = [%g, %g] rad/s. Loop broken at the actuator ' ...
        'command u. Primary W_u = diag(%s) (rated torque), alternate W_u = diag(%s). ' ...
        'Truncation: %s Controller %s (continuous time, delay %g ms nominal). Disk-margin ' ...
        'requirement b >= %.4f (gamma = %.2f). Spectral gap = sigma_2 - sigma_min at omega*. ' ...
        'D+- = h * one-sided envelope derivative.\n\n'], ...
        configuration.provenance.structuralModel, rows(1).plantStateCount, rows(2).plantStateCount, ...
        rows(1).stability.stateCount, configuration.search.bandRadiansPerSecond(1), ...
        configuration.search.bandRadiansPerSecond(2), ...
        mat2str(configuration.scaling.primaryActuatorScale', formats.shortVectorDigits), ...
        mat2str(configuration.scaling.alternateActuatorScale', formats.shortVectorDigits), ...
        configuration.truncation.ruleDescription, configuration.controller.versionLabel, ...
        configuration.operatingPoint.delaySeconds * unitConstants.secondsToMilliseconds, ...
        configuration.requirements.diskMarginRequirement, ...
        configuration.requirements.inputSensitivityPeakBound);

    fprintf(fileIdentifier, '# Table 2. Equal-error comparison with the dense baseline\n\n');
    totals = terra.summarizeDenseBaseline(results);
    header = {'Quantity', 'Adaptive method', 'Plain dense grid (equal error)'};
    cells = {
        'Valleys detected / reference', sprintf('%d / %d', totals.methodMatched, totals.referenceValleys), ...
            sprintf('%d / %d', totals.denseMatched, totals.referenceValleys);
        'Extra (spurious) valleys', sprintf('%d', totals.methodExtra), sprintf('%d', totals.denseExtra);
        'Max band-minimum error', sprintf('%.2e', totals.methodMaximumError), ...
            sprintf('%.2e', totals.denseMaximumError);
        'Grid points', sprintf('%d + modal points', configuration.search.initialGridPointCount), ...
            sprintf('median %d (range %d-%d); target missed in %d cases', ...
            round(totals.denseMedianPoints), totals.denseMinimumPoints, ...
            totals.denseMaximumPoints, totals.denseFailures);
        'Median f_W evaluations', sprintf('%d', round(totals.methodMedianEvaluations)), ...
            sprintf('%d (median ratio %.1f)', round(totals.denseMedianEvaluations), ...
            totals.medianEvaluationRatio);
        'Median wall time (ms)', sprintf('%.1f', totals.methodMedianMilliseconds), ...
            sprintf('%.1f (median ratio %.1f)', totals.denseMedianMilliseconds, ...
            totals.medianTimeRatio);
        'Median fixed model-build time (ms, shared)', sprintf('%.1f', totals.modelMedianMilliseconds), ...
            sprintf('%.1f', totals.modelMedianMilliseconds);
        'Max switch-location error', totals.methodSwitchErrorText, totals.denseSwitchErrorText;
        'Band edges certified by tail bounds', sprintf('%d / %d cases', totals.edgesVerified, ...
            totals.caseCount), sprintf('%d / %d cases', totals.edgesVerified, totals.caseCount)};
    terra.writeMarkdownTable(fileIdentifier, header, cells);
    fprintf(fileIdentifier, ['Single main crossover check (reported alongside): misses the active ' ...
        'valley in %d of %d cases; largest margin overestimate %.4f.\n\n'], ...
        totals.crossoverMissCount, totals.caseCount, totals.crossoverMaximumOverestimate);
    fprintf(fileIdentifier, ['Software/hardware: %s %s on %s; processor: %s; logical ' ...
        'processors: %s. Method and dense times are medians of %d repeats on this machine ' ...
        '(the model build is timed once); they are not portable speed claims.\n'], ...
        results.environment.interpreter, results.environment.version, ...
        results.environment.platform, results.environment.processor, ...
        results.environment.processorCount, configuration.baseline.timingRepeatCount);
end
